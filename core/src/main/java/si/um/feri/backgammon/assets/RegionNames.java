package si.um.feri.backgammon.assets;

import si.um.feri.backgammon.model.Side;

public final class RegionNames {
    // gameplay.atlas
    public static final String MENU_BACKGROUND = "menu-background";
    public static final String BACKGROUND = "background";
    public static final String SPIKE_INTRO_BRIGHT = "spike-bright-intro";
    public static final String SPIKE_INTRO_DARK = "spike-dark-intro";
    public static final String FIGURE_BRIGHT = "figure-bright";
    public static final String FIGURE_DARK = "figure-dark";
    public static final String FIGURE_SIDE_BRIGHT = "figure-bright-side";
    public static final String FIGURE_SIDE_DARK = "figure-dark-side";
    private static final String DICE_PREFIX = "dice-val-";

    // uiskin.atlas (generated by tools/generate_ui_assets.py)
    public static final String RING = "ring";
    public static final String GLOW = "glow";
    public static final String GLOW_RECT = "glow-rect";
    public static final String POINT_GLOW = "point-glow";
    public static final String PILL = "pill";
    public static final String PANEL = "panel";
    public static final String PANEL_ACTIVE = "panel-active";
    public static final String WHITE = "white";

    private RegionNames() {
    }

    public static String checker(Side side) {
        return side == Side.BRIGHT ? FIGURE_BRIGHT : FIGURE_DARK;
    }

    public static String checkerEdge(Side side) {
        return side == Side.BRIGHT ? FIGURE_SIDE_BRIGHT : FIGURE_SIDE_DARK;
    }

    public static String dice(int value) {
        return DICE_PREFIX + value;
    }
}
